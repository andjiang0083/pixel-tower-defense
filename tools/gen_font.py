# lowercase reuses uppercase shapes (retro-terminal convention)
for c in "abcdefghijklmnopqrstuvwxyz":
    GLYPHS[c] = GLYPHS[c.upper()]

# undefined symbol -> open box, so a typo in UI text is visible on screen
FALLBACK = "11111 10000 10000 10000 10000 10000 11111"

FIRST, LAST = 32, 126
rows, fallbacks = [], []
for c in range(FIRST, LAST + 1):
    g = GLYPHS.get(chr(c))
    if g is None:
        fallbacks.append(chr(c)); g = FALLBACK
    parts = g.split()
    assert len(parts) == FONT_H, (chr(c), "rows=%d" % len(parts))
    for p in parts:
        assert len(p) == FONT_W, (chr(c), "cols=%s" % p)
    rows.append("  /* %c */ {%s}," % (chr(c), ",".join("0x%02X" % int(p, 2) for p in parts)))

HEART = GLYPHS['♥'].split()
BLOCK = GLYPHS['█'].split()

