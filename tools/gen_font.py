open("src/pixel_font.h", "w").write(out)
print("wrote src/pixel_font.h : %d glyphs (%d via fallback: %r)"
      % (LAST - FIRST + 1, len(fallbacks), "".join(sorted(set(fallbacks)))))


# ── ASCII preview: eyeball readability before touching hardware ─────────────
def glyph(ch):
    return (GLYPHS.get(ch) or FALLBACK).split()

def banner(text):
    lines = [""] * FONT_H
    for c in text:
        g = glyph(c)
        for i in range(FONT_H):
            lines[i] += g[i].replace('1', '#').replace('0', '.') + "."
    return "\n".join(lines)

for t in ["HP 20", "$150 WAVE 3", "NEXT WAVE!", "GAME OVER",
          "TAP MAP TO BUILD"]:
    print("\n" + banner(t))
