#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
# gen_cnfont.py — 生成 src/cn_font.h（16x16 中文点阵，零文件资源铁律）
# ----------------------------------------------------------------------------
# 收字范围 = src/i18n.h 的 STR_CN 表（界面中文真源）。渲染用 macOS 自带
# STHeiti Medium.ttc；其他平台把 FONT_PATH 换成本地中文字体即可。
# 二值化阈值 128：16px 汉字点阵下笔画清晰、不断连。
#
# 用法：python3 tools/gen_cnfont.py   # 输出 src/cn_font.h（提交前必跑）
# 依赖：Pillow（pip install Pillow）
# 字体：默认按平台挑候选；可用环境变量 CN_FONT 指定任意中文字体文件。
#
# ⚠️ 字节一致性纪律：点阵由 Pillow+FreeType 光栅化外部字体得到，换字体/换平台/
# 升级依赖都会得到不同字节（实测同机 STHeiti vs Hiragino 即不同）。所以：
#   - 提交前用**同一字体**重跑，git diff 必须为空（维护机纪律）；
#   - CI 不做字节级漂移，改查语义覆盖：tools/check_cnfont.py（纯 stdlib）。
# 想在不同机器上复现入库字节，设 CN_FONT 指向生成时用的那个字体文件。
import os, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from cn_glyph_rule import collect_from_i18n          # 收字规则单一真源（与 CI 检查器共用）
FONT_CANDIDATES = [
    "/System/Library/Fonts/STHeiti Medium.ttc",                    # macOS
    "/System/Library/Fonts/Hiragino Sans GB.ttc",                  # macOS 备选
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",      # Linux
    "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc",                # Linux 文泉驿
]
FONT_PATH = os.environ.get("CN_FONT") or next(
    (p for p in FONT_CANDIDATES if pathlib.Path(p).exists()), None)
if not FONT_PATH:
    sys.exit("FATAL: no CJK font found; set CN_FONT=/path/to/font.ttf")
OUT = ROOT / "src" / "cn_font.h"
SZ = 16                       # 点阵边长
BYTES_PER_GLYPH = SZ * 2      # 每行 2 字节（bit15 = 最左列）

def collect_chars():
    """收字范围 = i18n.h STR_CN 表里所有非 ASCII 字符。

    v0.4.3：此前只收 U+4E00..9FFF 汉字，全角标点"："和"！"因此从未进字库，
    渲染时被 px_cnChar 静默跳过（中文标题/提示直接缺笔画）。规则现在是
    "非 ASCII 都要字形"，与 cn_glyph_rule.py / check_cnfont.py 同源。
    """
    return collect_from_i18n(ROOT)

def render(ch):
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(FONT_PATH, SZ)
    img = Image.new("L", (SZ, SZ), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 0), ch, fill=255, font=font)
    px = img.load()
    rows = []
    for y in range(SZ):
        hi = lo = 0
        for x in range(SZ):
            if px[x, y] >= 128:
                if x < 8: hi |= 1 << (7 - x)
                else:     lo |= 1 << (15 - x)
        rows.append(hi); rows.append(lo)
    return rows

def main():
    chars = collect_chars()
    if not chars:
        sys.exit("FATAL: no CJK chars collected")
    lines = []
    lines.append("// SPDX-License-Identifier: MIT")
    lines.append("// Copyright (c) 2026 andjiang0083")
    lines.append("// cn_font.h -- GENERATED by tools/gen_cnfont.py. DO NOT EDIT BY HAND.")
    lines.append("// 16x16 中文点阵；字表 = src/i18n.h 的 STR_CN 表（界面中文真源）。")
    lines.append("// 行字节：每行 2 字节，bit15 = 最左列（与 pixel_font.h 同序）。")
    lines.append("#pragma once")
    lines.append("#include <stdint.h>")
    lines.append("#define CN_FONT_W 16")
    lines.append("#define CN_FONT_H 16")
    lines.append("")
    lines.append("struct CnGlyph { const char* utf8; uint8_t rows[%d]; };" % BYTES_PER_GLYPH)
    lines.append("")
    lines.append("static const CnGlyph CN_GLYPHS[] = {")
    empty = []
    for ch in chars:
        rows = render(ch)
        if not any(rows):
            empty.append(ch); continue
        hexs = ",".join("0x%02X" % b for b in rows)
        # UTF-8 转义（保持 ASCII 安全，避免源码编码问题）
        esc = "".join("\\x%02X" % b for b in ch.encode("utf-8"))
        lines.append('  { "%s", { %s } },' % (esc, hexs))
    lines.append("};")
    lines.append("#define CN_GLYPH_COUNT ((int)(sizeof(CN_GLYPHS)/sizeof(CN_GLYPHS[0])))")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("gen_cnfont: %d glyphs -> src/cn_font.h (%d bytes)"
          % (len(chars) - len(empty), OUT.stat().st_size))
    if empty:
        sys.exit("FATAL: glyphs rendered empty (font missing these?): %s" % "".join(empty))

if __name__ == "__main__":
    main()
